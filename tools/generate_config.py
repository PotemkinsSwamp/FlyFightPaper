"""Deterministic JSON -> Luau, Python standard library only."""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
JSON_TYPES = '''-- Generated by tools/generate_config.py; do not edit.
local kinds = setmetatable({}, { __mode = "k" })
local Types = {}
Types.Null = table.freeze({})
function Types.array(value)
    kinds[value] = "array"
    return value
end
function Types.map(value)
    kinds[value] = "map"
    return value
end
function Types.kind(value)
    if value == Types.Null then return "null" end
    return kinds[value] or type(value)
end
return table.freeze(Types)
'''


def quote(value: str) -> str:
    """Use UTF-8 bytes with fixed-width decimal escapes, valid in Luau."""
    parts = []
    for byte in value.encode("utf-8"):
        if 32 <= byte <= 126 and byte not in (34, 92):
            parts.append(chr(byte))
        else:
            parts.append("\\" + f"{byte:03d}")
    return '"' + ''.join(parts) + '"'


def encode(value, depth=0) -> str:
    if value is None:
        return "JSONTypes.Null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        if not math.isfinite(value):
            raise ValueError("Nonfinite numbers cannot be represented")
        if isinstance(value, int) and abs(value) > 2**53:
            raise ValueError("Integer exceeds exact Luau double range")
        return repr(value)
    if isinstance(value, str):
        return quote(value)
    if isinstance(value, (list, dict)):
        kind = "array" if isinstance(value, list) else "map"
        entries = enumerate(value, 1) if kind == "array" else sorted(value.items())
        lines = []
        for key, item in entries:
            index = str(key) if kind == "array" else quote(key)
            lines.append("    " * (depth + 1) + f"[{index}] = {encode(item, depth + 1)},")
        if not lines:
            return f"JSONTypes.{kind}({{}})"
        return f"JSONTypes.{kind}({{\n" + "\n".join(lines) + "\n" + "    " * depth + "})"
    raise TypeError(f"Unsupported JSON type: {type(value)}")


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def load_json(data: bytes):
    return json.loads(data.decode("utf-8"), object_pairs_hook=unique_object,
                      parse_constant=lambda value: (_ for _ in ()).throw(ValueError(value)))


def module_name(stem: str) -> str:
    parts = re.findall(r"[A-Za-z0-9]+", stem)
    if not parts:
        raise ValueError(f"Invalid config stem: {stem}")
    return ''.join("AI" if part.lower() == "ai" else part[0].upper() + part[1:]
                   for part in parts)


def write_text(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(content.encode("utf-8"))


def generate(config_dir: Path, output_dir: Path) -> dict:
    outputs = {"JSONTypes.luau": JSON_TYPES}
    records = []
    used = {"jsontypes"}
    for path in sorted(config_dir.glob("*.json")):
        name = module_name(path.stem)
        if name.casefold() in used:
            raise ValueError(f"Config module name collision: {name}")
        used.add(name.casefold())
        raw = path.read_bytes()
        value = load_json(raw)
        code = '-- Generated by tools/generate_config.py; do not edit.\n'
        code += 'local JSONTypes = require(script.Parent.JSONTypes)\nreturn ' + encode(value) + '\n'
        outputs[name + ".luau"] = code
        records.append({"json": path.name, "module": name, "output": name + ".luau"})
    if not records:
        raise ValueError("No JSON configs found")
    # Validate all input before replacing anything. This directory belongs to this generator.
    output_dir.mkdir(parents=True, exist_ok=True)
    for stale in output_dir.glob("*.luau"):
        if stale.name not in outputs:
            stale.unlink()
    for name, content in outputs.items():
        write_text(output_dir / name, content)
    return {"configs": records}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config-dir", type=Path, default=ROOT / "config")
    parser.add_argument("--output-dir", type=Path, default=ROOT / "src/generated")
    args = parser.parse_args()
    manifest = generate(args.config_dir, args.output_dir)
    print(f"Generated {len(manifest['configs'])} config modules and JSONTypes")


if __name__ == "__main__":
    main()
